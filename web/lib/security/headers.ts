/**
 * Security headers, as pure functions (edge-safe: no Node APIs, no env reads). middleware.ts
 * puts them on every response it sees (pages, route handlers, /t/*, /api/*, redirects);
 * next.config.ts repeats the nonce-free ones for what its matcher skips (files with an extension
 * served by Next.js); public/_headers carries them for what Cloudflare serves from its asset
 * store before any code runs. One table of values serves all three.
 *
 * - Content-Security-Policy is built per request around a fresh nonce. Next.js 15 reads the
 *   nonce from the REQUEST's content-security-policy header and puts it on its own scripts, so
 *   the policy needs `strict-dynamic` and no host allow-list for scripts.
 * - Permissions-Policy keeps `camera=(self)` (the placard scanner) and `microphone=(self)`
 *   (Table talk): never deny them, the app breaks. Everything else it does not use is off.
 * - Referrer-Policy is `strict-origin-when-cross-origin` everywhere except the sign-in pages,
 *   where a link token or an email must never leave in a Referer (`no-referrer`).
 * - Strict-Transport-Security is never sent under `next dev` (http://localhost).
 */

export interface HeaderPair {
    key: string
    value: string
}

/**
 * Two years, subdomains included. Deliberately no `preload`: putting hackillinois.org on the
 * browsers' preload list is the org's call (it is hard to undo), not this app's.
 */
export const HSTS = "max-age=63072000; includeSubDomains"

export const PERMISSIONS_POLICY =
    "camera=(self), microphone=(self), geolocation=(), payment=(), usb=()"

export const REFERRER_DEFAULT = "strict-origin-when-cross-origin"
export const REFERRER_NONE = "no-referrer"

/**
 * The paths whose pages and redirects carry a sign-in token, an email or a placard token in
 * their URL or Referer: `/login`, everything under `/auth`, and everything under `/t` (the placard
 * QR's `/t/<CODE>?k=…`; app/t/[code]/route.ts sets `no-referrer` itself, but the middleware's
 * value is the one that reaches the browser, so it has to say the same).
 */
export function referrerPolicyFor(pathname: string): string {
    const p = pathname.replace(/\/+$/, "") || "/"
    return p === "/login" ||
        p === "/auth" ||
        p.startsWith("/auth/") ||
        p === "/t" ||
        p.startsWith("/t/")
        ? REFERRER_NONE
        : REFERRER_DEFAULT
}

/**
 * Every header that does not depend on the request except the Referrer-Policy: HSTS (not in
 * development), nosniff, framing, the camera/microphone policy and COOP.
 */
export function baseSecurityHeaders({ dev }: { dev: boolean }): HeaderPair[] {
    return [
        ...(dev ? [] : [{ key: "Strict-Transport-Security", value: HSTS }]),
        { key: "X-Content-Type-Options", value: "nosniff" },
        { key: "X-Frame-Options", value: "DENY" },
        { key: "Permissions-Policy", value: PERMISSIONS_POLICY },
        { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
    ]
}

/**
 * What public/_headers must say: Cloudflare serves files from public/ and _next/static straight
 * from its asset store, so neither the middleware nor next.config.ts ever sees them. Same values
 * as baseSecurityHeaders (production), plus the one-year immutable cache for hashed build files.
 * lib/__tests__/prod-headers.test.ts fails when the file drifts from this.
 */
export function cloudflareHeadersFile(): string {
    const base = [
        ...baseSecurityHeaders({ dev: false }),
        { key: "Referrer-Policy", value: REFERRER_DEFAULT },
    ]
    return [
        "# GENERATED by cloudflareHeadersFile() in lib/security/headers.ts; the test in",
        "# lib/__tests__/prod-headers.test.ts fails when this drifts. To rewrite it, from web/:",
        "#   npm run headers:file",
        "/*",
        ...base.map((h) => `  ${h.key}: ${h.value}`),
        "",
        "/_next/static/*",
        "  Cache-Control: public, max-age=31536000, immutable",
        "",
    ].join("\n")
}

/** A fresh CSP nonce: 128 random bits, base64. Edge-safe (Web Crypto, btoa). */
export function cspNonce(): string {
    const bytes = new Uint8Array(16)
    crypto.getRandomValues(bytes)
    let bin = ""
    for (const b of bytes) bin += String.fromCharCode(b)
    return btoa(bin)
}

/** A nonce is spliced into a header: only base64 / base64url characters get through. */
const NONCE = /^[A-Za-z0-9+/_-]{16,}={0,2}$/

/**
 * A host a CSP source can carry as it is: letters, digits, dots and hyphens (a DNS name or an
 * IPv4 address), or a bracketed IPv6 address. The URL parser percent-decodes a host and accepts
 * `;`, `,` and `*` in it, so `https://x.com%3Bscript-src` parses to the origin
 * `https://x.com;script-src`, which would open a new directive in the policy.
 */
const SOURCE_HOST =
    /^(?:[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?|\[[0-9A-Fa-f:.]+\])$/

/**
 * `https://adonix.hackillinois.org` out of an ADONIX_URL value, or null when it is not an
 * http(s) URL with a plain host. Staff Google sign-in leaves through adonix, so it is the one
 * cross-origin form target the policy has to name; a value that could change the policy
 * (`;`, `,`, `*`, a quote, whitespace) gives null instead.
 */
export function originOf(url: string | null | undefined): string | null {
    if (!url) return null
    try {
        const u = new URL(url.trim())
        if (u.protocol !== "https:" && u.protocol !== "http:") return null
        if (!SOURCE_HOST.test(u.hostname)) return null
        return u.origin
    } catch {
        return null
    }
}

export interface CspOptions {
    nonce: string
    /** `next dev`: React needs eval for refresh/source maps and HMR needs a WebSocket. */
    dev?: boolean
    /**
     * `next dev --turbopack` (npm run dev): it inserts some route chunks without the nonce, which
     * `strict-dynamic` would block, so 'self' has to count there. Webpack's dev server (`npx next
     * dev`) and every production build keep `strict-dynamic`.
     */
    turbopack?: boolean
    /** adonix's origin: the staff Google sign-in is a redirect through it. */
    adonixOrigin?: string | null
}

/**
 * The Content-Security-Policy for one request.
 *
 * - script-src: our files, the request's nonce, and `strict-dynamic` so the scripts Next.js
 *   loads from those inherit trust (a browser that knows strict-dynamic ignores 'self').
 *   `next dev` adds 'unsafe-eval' (React's refresh needs eval). Under Turbopack (`npm run dev`)
 *   it also drops `strict-dynamic`: some route chunks (a loading.tsx boundary's) are inserted
 *   without the nonce, which only 'self' lets through.
 * - style-src keeps 'unsafe-inline': React inline `style` attributes and next/font's rules.
 * - media-src / worker-src / img-src take blob:, for the recorder's playback and the scanner.
 * - connect-src is 'self': the browser only ever calls this origin (adonix is called by the
 *   server).
 * - form-action: this origin, plus adonix, because Chrome checks the targets of redirects that
 *   follow a form post too.
 */
export function contentSecurityPolicy({
    nonce,
    dev = false,
    turbopack = false,
    adonixOrigin = null,
}: CspOptions): string {
    if (!NONCE.test(nonce)) throw new Error("CSP nonce must be base64")
    const script = [
        "'self'",
        `'nonce-${nonce}'`,
        ...(dev ? ["'unsafe-eval'"] : []),
        ...(dev && turbopack ? [] : ["'strict-dynamic'"]),
    ]
    const connect = ["'self'", ...(dev ? ["ws:"] : [])]
    const form = ["'self'", ...(adonixOrigin ? [adonixOrigin] : [])]
    return [
        "default-src 'self'",
        `script-src ${script.join(" ")}`,
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: blob:",
        "media-src 'self' blob:",
        "font-src 'self' data:",
        `connect-src ${connect.join(" ")}`,
        "worker-src 'self' blob:",
        "frame-ancestors 'none'",
        "base-uri 'self'",
        `form-action ${form.join(" ")}`,
        "object-src 'none'",
    ].join("; ")
}

/** The nonce a policy carries (what Next.js reads from the request header), or null. */
export function nonceOf(csp: string | null | undefined): string | null {
    const m = /(?:^|;)\s*script-src[^;]*'nonce-([^']+)'/.exec(csp ?? "")
    return m ? m[1] : null
}

export interface ApplyOptions {
    pathname: string
    dev: boolean
    /** The response's Content-Security-Policy; omitted for files the middleware never sees. */
    csp?: string
}

/**
 * Put the security headers on a response. A Referrer-Policy the response already carries stays
 * (the magic-link, scan and bearer-strip redirects set `no-referrer` themselves).
 */
export function applySecurityHeaders(
    headers: Headers,
    { pathname, dev, csp }: ApplyOptions,
): void {
    for (const { key, value } of baseSecurityHeaders({ dev }))
        headers.set(key, value)
    if (!headers.has("Referrer-Policy"))
        headers.set("Referrer-Policy", referrerPolicyFor(pathname))
    if (csp) headers.set("Content-Security-Policy", csp)
}
