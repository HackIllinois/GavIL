import nextCoreWebVitals from "eslint-config-next/core-web-vitals"
import nextTypescript from "eslint-config-next/typescript"

/**
 * The same rule set `next lint` ran on Next.js 15 (next/core-web-vitals + next/typescript, plus the
 * two overrides below), now through the ESLint CLI (`npm run lint` = `eslint .`): Next.js 16 removed
 * `next lint`.
 *
 * eslint-config-next 16 also switches on the React Compiler diagnostics that ship in
 * eslint-plugin-react-hooks 7 (set-state-in-effect, refs, purity, immutability, ...). Gav-IL does
 * not use the React Compiler and its screens were written and tested without them (the offline
 * outbox, timers and toasts do their setState in effects on purpose), so they stay off to keep the
 * rules identical to Next 15: `rules-of-hooks` (error) and `exhaustive-deps` (warn) are the two
 * react-hooks rules that always applied, and they still do. Turning any of these on is a separate
 * piece of work, one screen at a time.
 */
const REACT_COMPILER_RULES = [
    "static-components",
    "use-memo",
    "preserve-manual-memoization",
    "incompatible-library",
    "immutability",
    "globals",
    "refs",
    "set-state-in-effect",
    "error-boundaries",
    "purity",
    "set-state-in-render",
    "unsupported-syntax",
    "config",
    "gating",
]

const config = [
    ...nextCoreWebVitals,
    ...nextTypescript,
    {
        rules: {
            ...Object.fromEntries(
                REACT_COMPILER_RULES.map((r) => [`react-hooks/${r}`, "off"]),
            ),
            "@typescript-eslint/no-explicit-any": "error",
            "@typescript-eslint/no-unused-vars": [
                "error",
                {
                    vars: "all",
                    args: "after-used",
                    argsIgnorePattern: "^_",
                    varsIgnorePattern: "^_",
                    ignoreRestSiblings: true,
                },
            ],
        },
    },
    {
        // `eslint .` scans the whole project tree (`next lint` only looked at app/, components/, lib/ ...),
        // so every directory a script of this package generates must be listed here, gitignored or not:
        // `.next` (dev/build), `.open-next` (build:worker), `.wrangler` (preview/deploy: wrangler bundles
        // the Worker into `.wrangler/tmp/`, which is bundled generated JS with thousands of findings).
        ignores: [
            ".next/**",
            ".open-next/**",
            ".wrangler/**",
            "node_modules/**",
            "cloudflare-env.d.ts",
            // Generated by Next.js (triple-slash references are its format).
            "next-env.d.ts",
        ],
    },
]

export default config
